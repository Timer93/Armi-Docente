import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ZipArchive } from 'archiver';
import sharp from 'sharp';
const source = path.resolve('extensions/armi-student-access');
fs.mkdirSync(path.join(source,'icons'),{recursive:true});
const icon=fs.readFileSync(path.resolve('src/Logo_bar.ico')),offset=icon.readUInt32LE(18),length=icon.readUInt32LE(14);
const png=icon.subarray(offset,offset+length);
for(const size of [16,32,48,128]) await sharp(png).resize(size,size).png().toFile(path.join(source,'icons',`${size}.png`));
const manifestPath=path.join(source,'manifest.json'),manifest=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
if(!manifest.key)manifest.key=crypto.generateKeyPairSync('rsa',{modulusLength:2048}).publicKey.export({type:'spki',format:'der'}).toString('base64');
manifest.version='1.1.0';if(!manifest.permissions.includes('nativeMessaging'))manifest.permissions.push('nativeMessaging');fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
const files=[];
const walk=folder=>{for(const entry of fs.readdirSync(folder,{withFileTypes:true})){const full=path.join(folder,entry.name);if(entry.isDirectory())walk(full);else files.push(full);}};walk(source);
const inventory=files.map(file=>({path:path.relative(source,file).replaceAll('\\','/'),sha256:crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')}));
const output=path.resolve('public/extensions/ARMI-Estudiantes.zip');fs.mkdirSync(path.dirname(output),{recursive:true});
await new Promise((resolve,reject)=>{const stream=fs.createWriteStream(output);const zip=new ZipArchive({zlib:{level:9}});stream.on('close',resolve);stream.on('error',reject);zip.on('error',reject);zip.pipe(stream);
 for(const file of files)zip.file(file,{name:`ARMI-Estudiantes/extension/${path.relative(source,file).replaceAll('\\','/')}`});
 for(const file of ['Instalar.ps1','LEEME.html'])zip.file(path.join('extensions/installer',file),{name:`ARMI-Estudiantes/${file}`});
 zip.append(JSON.stringify(inventory,null,2),{name:'ARMI-Estudiantes/archivos.json'});zip.finalize();});
console.log(`Extensión empaquetada: ${output} (${fs.statSync(output).size} bytes)`);
