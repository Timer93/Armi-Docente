import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { createInteractiveAttemptStore, isMobilePracticeDevice, PRACTICE_PERIOD_MS } from '../backend/interactiveAttemptStore.js';

const db = new Database(':memory:');
let clock = 1_000_000;
let store = createInteractiveAttemptStore(db, { now: () => clock });
const key = { sessionId: 'lesson', activityId: 'practice', mode: 'individual', scopeKey: 'student' };
try {
  assert.equal(store.publicState(store.get(key)).status, 'ready');
  const first = store.start(key);
  assert.equal(first.deadline, clock + PRACTICE_PERIOD_MS);
  assert.throws(() => store.start(key), /comenzar de nuevo/);
  const checkpoint = { state: { question: 3, answers: [1, 2], order: [3, 1, 2], score: 8 }, score: 8, maxScore: 20 };
  store.save(key, first.token, checkpoint);
  clock += 120_000;
  store = createInteractiveAttemptStore(db, { now: () => clock });
  assert.equal(store.get(key).deadline_ms, first.deadline, 'Restart does not reset the deadline');
  assert.throws(() => store.save(key, 'wrong-window', {}), /esta ventana/);
  assert.throws(() => store.grant(key), /Solo se pueden ampliar/);
  clock = first.deadline;
  assert.equal(store.get(key).status, 'paused');
  assert.throws(() => store.complete(key, first.token), /agotó/);
  assert.throws(() => store.save(key, first.token, { ...checkpoint, score: 20 }), /agotó/);
  store.grant(key);
  const continued = store.resume(key);
  assert.deepEqual(continued.checkpoint, checkpoint, 'Question 3, answers and shuffled order survive continuation');
  assert.equal(continued.stage, 2);
  assert.equal(continued.deadline, clock + PRACTICE_PERIOD_MS);
  assert.notEqual(continued.token, first.token);
  assert.throws(() => store.resume(key), /ampliación/);
  clock = continued.deadline;
  assert.equal(store.get(key).status, 'expired');
  assert.throws(() => store.start(key), /comenzar de nuevo/);
  assert.throws(() => store.grant(key), /Solo se pueden ampliar/);
  store.reset(key);
  const fresh = store.start(key);
  store.abandon(key, fresh.token);
  assert.equal(store.get(key).status, 'abandoned');
  assert.throws(() => store.start(key), /comenzar de nuevo/);
  store.reset(key);
  const final = store.start(key); store.complete(key, final.token);
  assert.throws(() => store.complete(key, final.token), /agotó/);
  assert.equal(store.get(key).status, 'completed');
  assert.equal(isMobilePracticeDevice('Android'), true);
  assert.equal(isMobilePracticeDevice('Mozilla Macintosh', { maxTouchPoints: 5, screenShortSide: 900 }), true, 'iPad desktop mode');
  assert.equal(isMobilePracticeDevice('Mozilla Windows', { maxTouchPoints: 5, screenShortSide: 390 }), true, 'Phone desktop mode');
  assert.equal(isMobilePracticeDevice('Mozilla Linux x86_64', { platform: 'Android', maxTouchPoints: 5, screenShortSide: 980 }), true, 'Android desktop UA and viewport');
  assert.equal(isMobilePracticeDevice('Mozilla Windows', { maxTouchPoints: 10, screenShortSide: 1080 }), false, 'Desktop touchscreen');
  console.log('OK: persistent deadlines, single attempt, immutable first timeout, retained question/order, only one continuation, final expiration, abandonment and mobile signals.');
} finally { db.close(); }
