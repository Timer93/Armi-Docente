import assert from 'node:assert/strict';
import { createTransferProgress } from '../backend/transferProgress.js';

const progress = createTransferProgress();
assert.equal(progress.snapshot().state, 'idle');
progress.begin('a', 100);
progress.begin('b', 300);
progress.update('a', 100);
assert.equal(progress.snapshot().state, 'transferring', 'Copied bytes still require validation');
assert.equal(progress.snapshot().completedFiles, 0);
progress.complete('a');
progress.update('b', 150);
assert.equal(progress.snapshot().totalBytes, 400, 'Completing one file must not shrink the concurrent denominator');
assert.equal(progress.snapshot().completedBytes, 250);
progress.complete('b');
assert.equal(progress.snapshot().state, 'complete');
assert.equal(progress.snapshot().completedFiles, 2);
assert.equal(progress.snapshot().completedBytes, 400, 'Completion remains observable after file entries are removed');
progress.begin('c', 0);
assert.equal(progress.snapshot().totalFiles, 1, 'A new cycle resets the previous totals');
progress.complete('c');
assert.equal(progress.snapshot().state, 'complete', 'Empty files can also complete');
progress.begin('missing', 500, 'waiting');
assert.equal(progress.snapshot().state, 'waiting');
progress.begin('missing', 500);
progress.update('missing', 500);
progress.fail('missing', 'Checksum mismatch');
assert.equal(progress.snapshot().state, 'error', 'Copying all bytes is not proof of a valid download');
progress.begin('missing', 500);
progress.complete('missing');
assert.equal(progress.snapshot().state, 'complete');
console.log('OK: descargas simultaneas, totales estables, finalizacion persistente, archivos vacios y reintentos.');
